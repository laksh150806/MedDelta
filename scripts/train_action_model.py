"""Train a reproducible, tiny text classifier and export browser-readable weights.

Only synthetic training templates are used. Evaluation templates are never read
into training. No medical data, model service, or GPU is needed.
"""
import json
import re
from pathlib import Path
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression

ROOT = Path(__file__).resolve().parents[1]

def expand(templates, medicines):
    rows = []
    for label, families in templates.items():
        for family, template in enumerate(families):
            for medicine in medicines:
                for amount, frequency in [(5, 'once daily'), (10, 'twice daily'), (20, 'once weekly')]:
                    regimen = f'{amount} mg orally {frequency}'
                    text = template.format(medicine=medicine, regimen=regimen, instruction=f'{medicine} {regimen}')
                    rows.append({'text': text, 'label': label, 'family': f'{label}-{family}'})
    return rows

def main():
    templates = json.loads((ROOT/'data/action-templates.json').read_text())
    # Learn only action wording. Medicine names and dosage/schedule text must not
    # become shortcuts for a start/stop decision.
    rows = [{'text': template.split('{', 1)[0].strip(), 'label': label}
            for label, families in templates['train'].items() for template in families]
    vectorizer = CountVectorizer(lowercase=True, token_pattern=r'(?u)\b[a-z]+\b', ngram_range=(1, 2))
    features = vectorizer.fit_transform([r['text'] for r in rows])
    model = LogisticRegression(C=8.0, max_iter=1000, random_state=17).fit(features, [r['label'] for r in rows])
    payload = {
        'version': 'action-linear-v1', 'algorithm': 'multinomial logistic regression, word unigram/bigram counts',
        'training_examples': len(rows), 'training_template_families': sum(map(len, templates['train'].values())),
        'classes': model.classes_.tolist(), 'vocabulary': vectorizer.vocabulary_,
        'coefficients': model.coef_.round(10).tolist(), 'intercepts': model.intercept_.round(10).tolist(),
        'limitations': 'Synthetic software-development data only. Scores are uncalibrated. All expanded extraction requires human confirmation. No clinical validation.'
    }
    path = ROOT/'dist/action-model.js'
    path.write_text('// Generated by scripts/train_action_model.py. Do not edit weights manually.\nexport default '+json.dumps(payload, separators=(',', ':'))+';\n')
    parity = [{'text': r['text'], 'expected': str(model.predict(vectorizer.transform([r['text']]))[0]), 'scores': model.predict_proba(vectorizer.transform([r['text']]))[0].tolist()} for r in rows]
    (ROOT/'tests/model-parity.json').write_text(json.dumps(parity, indent=2)+'\n')
    print(f'Exported {len(rows)} synthetic training examples across {payload["training_template_families"]} template families; {len(vectorizer.vocabulary_)} features.')

if __name__ == '__main__':
    main()
